-- hyprland 설정 — 손으로 고치는 파일이다. 생성물이 아니다.
--
-- 살아있는 사본은 ~/.config/hypr/hyprland.lua 이고 평범한 쓰기 가능 파일이다.
-- 저장하면 하이프랜드가 바로 리로드하고, 문법이 깨진 편집은 에러만 찍고 직전
-- 설정이 계속 돈다. 그러니 저기서 굴리고, 레포 쪽은 시드 겸 백업으로 둔다
-- (../default.nix 의 활성화 스크립트가 파일이 *없을 때만* 복사한다).
--
-- ── 왜 .conf 가 아니라 .lua 인가 ────────────────────────────────────────────
-- 0.55 부터 hyprlang 이 deprecated 이고 설정은 Lua 다. 인터넷에 널린
-- hyprland.conf 예제는 그대로 안 붙는다 — `hyprconf2lua` 로 변환하거나 아래
-- 문법을 따라 쓴다. 값 이름 자체는 그대로라, 위키의 변수표는 여전히 유효하다.
--
-- ── 니리와의 관계 ──────────────────────────────────────────────────────────
-- 키 배치는 ../../niri/rice/config.kdl 에서 그대로 옮겼다. 두 세션을 오가며 쓸
-- 거라 근육기억이 갈리는 게 제일 큰 비용이기 때문이다. 레이아웃도 같은 이유로
-- dwindle 이 아니라 `scrolling` 이다 — 무한 띠 위에 컬럼이 쌓이는, 니리와 같은
-- 모델이다. 다만 1:1 은 아니고, 다른 곳마다 주석을 달아 뒀다.

-- 이 파일은 하이프랜드가 자동 생성한 게 아니다. 안 적으면 첫 실행에 "설정을
-- 만들어 줬다"는 안내가 뜬다.
hl.config({ autogenerated = false })


