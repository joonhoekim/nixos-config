-- 레이아웃마다 컬럼 키의 디스패처가 달라서, 값만 바꾸면 그 키들이 `Unknown layoutmsg` 로 조용히 죽는다.
-- dofile 인 이유는 decor.lua 와 같다. 손으로 고쳤으면 `apps/rice/layout --reload`.
-- 실패하면 scrolling 으로 떨어진다 — 키가 다 죽은 세션이 소리 없이 뜨면 고칠 수도 없다.
do
    local home = os.getenv("HOME")
    local name = "scrolling"
    local f = io.open(home .. "/.config/rice/layout")
    if f then
        name = f:read("l") or name
        f:close()
    end
    local ok, err = pcall(dofile, home .. "/.config/hypr/layouts/" .. name .. ".lua")
    if not ok then
        print("rice: layouts/" .. name .. ".lua 를 못 돌렸다 — " .. tostring(err) .. " — scrolling 으로 간다")
        if name ~= "scrolling" then
            dofile(home .. "/.config/hypr/layouts/scrolling.lua")
        end
    end
end


