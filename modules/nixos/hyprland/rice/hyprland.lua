-- 셸이 설정 GUI 와 matugen 으로 써 넣는 파일들. 색·커서·모니터·창 규칙이 여기서
-- 온다. 마지막에 부르므로 겹치는 값(gaps, rounding)은 DMS 쪽이 이긴다 — 레포
-- 값으로 되돌리고 싶으면 그 줄을 빼면 된다.
--
-- pcall 인 건 니리 include 의 `optional=true` 와 같은 뜻이다. 파일 하나가
-- 없다고 설정 전체가 죽으면 세션이 통째로 하이프랜드 기본값으로 떨어진다.
--
-- binds-user 는 DMS 설정 GUI 가 키를 추가할 때 쓰는 자리다(기본은 빈 파일).
-- 위에서 이미 잡은 키를 거기서 또 잡으면 둘 다 실행되니, 그럴 땐 그 파일에서
-- hl.unbind() 를 먼저 부른다.
for _, fragment in ipairs({ "colors", "cursor", "outputs", "windowrules", "layout", "binds-user" }) do
    pcall(require, "dms." .. fragment)
end
