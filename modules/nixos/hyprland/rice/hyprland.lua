-- general.layout 과 그 레이아웃에만 뜻이 있는 키들. ~/.config/hypr/layouts/
-- <이름>.lua 가 한 벌씩이고, 어느 것인지는 ~/.config/rice/layout 한 줄이 정한다.
-- 파일이 없으면 scrolling 이다 — 레포의 기본값이고, 레포에 둘 다 있다.
--
-- ── 왜 이 파일 안의 블록이 아니라 파일 하나씩인가 ───────────────────────
-- 레이아웃은 값 하나(general.layout)가 아니다. 컬럼 사이 이동·폭·합치기 키는
-- 레이아웃마다 **다른 디스패처**라, 값만 바꾸면 그 키들이 `Unknown layoutmsg`
-- 로 조용히 죽는다. 둘을 한 파일에 묶어 두면 그 어긋남이 생길 자리가 없다.
--
-- ── require 가 아니라 dofile 인 이유 ─────────────────────────────────────
-- decor.lua 와 같다. require 된 파일은 하이프랜드가 감시해서 저장할 때마다 설정
-- 전체가 리로드되고, 리로드는 걸어 둔 화면 셰이더까지 지운다. dofile 로 읽은
-- 파일은 감시 목록에 안 들어간다. 라이브 반영은 apps/rice/layout 이 eval 로
-- 한다 — 옛 파일이 걸었던 키를 풀고 새 파일을 돌리므로 리로드가 필요 없다.
-- 그러니 레이아웃 파일을 손으로 고쳤으면 `apps/rice/layout --reload`.
--
-- ── 실패하면 scrolling 으로 떨어진다 ─────────────────────────────────────
-- pcall 로 삼키고 끝내면 컬럼 키가 전부 죽은 세션이 소리 없이 뜬다. 문법이
-- 깨진 파일을 골라 뒀어도 기본 레이아웃의 키는 살아 있어야 고칠 수 있다.
do
    local home = os.getenv("HOME")
    local name = "scrolling"
    local f = io.open(home .. "/.config/rice/layout")
    if f then
        name = f:read("l") or name
        f:close()
    end
    local ok, err = pcall(dofile, home .. "/.config/hypr/layouts/" .. name .. ".lua")
    if not ok then
        print("rice: layouts/" .. name .. ".lua 를 못 돌렸다 — " .. tostring(err) .. " — scrolling 으로 간다")
        if name ~= "scrolling" then
            dofile(home .. "/.config/hypr/layouts/scrolling.lua")
        end
    end
end


