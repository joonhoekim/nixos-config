-- 이 세션이 존재하는 이유. 렌더링이 끝난 화면 한 장에 프래그먼트 셰이더를 한 번
-- 더 거는 훅이고, 니리에는 이게 없다.
--
-- ── 목록과 순환은 여기 없다 ───────────────────────────────────────────────
-- 예전에는 이 파일이 셰이더 셋을 배열로 들고 직접 순환했다. 지금은
-- `apps/rice/crt --next` 를 부른다. 옮긴 이유는 셰이더가 열 몇 장이 된 것보다
-- **체인** 쪽이 크다 — 여러 장을 겹치면 하이프랜드에 걸 파일을 만들어 내야
-- 하는데(apps/rice/chain), 그건 lua 설정 안에서 할 일이 아니다. 게다가 순환
-- 목록을 두 곳에 두면 갈래를 하나 늘릴 때마다 둘을 같이 고쳐야 하고, 안 고친
-- 쪽이 조용히 낡는다.
--
-- 그래서 이 자리에 남은 것은 "무엇으로 시작할까" 하나다.
--
-- ── 셰이더에 딸려 오는 두 축 ──────────────────────────────────────────────
-- 하나로 보이지만 둘이고, 서로 다른 조건에 묶인다. 한동안 이 둘을 하나로 묶어
-- 두는 바람에 증상이 둘 다 남았다 — docs/postmortems/2026-08-04-hyprland-crt.md.
--
-- debug:damage_tracking — 프레임을 그릴 때 *어디를* 그리는가
--   기준은 `time` 이 아니라 **셰이더가 자기 픽셀 밖을 읽는가** 다. 이 CRT 들은
--   전부 읽는다: curve() 는 배럴 왜곡이라 가장자리에서 수십 px 어긋난 곳을,
--   gun() 은 색수차로 ±3 px 를, bloom() 은 5 px 반경에 16 탭을 읽는다. 바뀐
--   사각형만 다시 합성하면 그 바깥 이웃이 낡아서 움직이는 것 둘레에 잔상이 남고,
--   stripes() 의 fwidth() 는 사각형 경계에서 불연속이라 스캔라인 세기가 사각형
--   모양으로 갈린다. 그래서 셰이더가 걸리면 무조건 0 이다.
--
-- debug:vfr — 프레임을 *그릴지 말지*
--   VFR 이 켜져 있으면 데미지가 없을 때 프레임을 아예 안 그린다. time 을 쓰는
--   셰이더는 거기서 멈춰서, 마우스를 움직여야 험 바가 한 칸 흐른다. 그래서 이쪽은
--   흐르는지로 갈린다 — 정지 셰이더는 화면이 바뀔 때만 다시 그리면 충분하고(실측:
--   damage 0 + vfr 켬으로 잔상 없음), 끄면 정지 화면을 주사율대로 다시 그리는
--   순수한 낭비가 된다.
--
--   판정은 `time` 유니폼이 있는지가 아니라 **흐르는 것을 여는 손잡이가 0 이 아닌지**
--   다. crt.frag 은 그레인·험 바·클릭 파문을 전부 0 으로 내리면 그 자리에서 정지
--   셰이더가 되고, 그때는 VFR 을 켜 두는 것이 맞다. 그 손잡이가 어느 것인지는
--   셰이더가 `!motion` 으로 스스로 선언한다(apps/rice/chain --motion).
--
-- 배터리 비용은 damage_tracking 이 아니라 이 vfr 쪽에 붙어 있다.
--
-- ── 이 줄은 리로드마다 다시 돈다 ──────────────────────────────────────────
-- 하이프랜드는 이 파일과 require 된 조각이 바뀔 때마다 설정을 통째로 다시
-- 읽는데, 그때 screen_shader 는 비워진다 — 리로드 평가 시점에는 hl.get_config
-- 도 빈 값을 준다(실측 2026-08-12). DMS 는 테마·간격이 바뀔 때마다 dms/ 조각을
-- 다시 쓰므로, **프로필 전환마다** 리로드가 일어난다. 여기서 이름 하나를 그대로
-- 걸면 그때마다 골라 둔 셰이더가 그 이름으로 되돌아간다(실제로 그랬다).
--
-- 그래서 --boot 다: 마지막으로 걸었던 것(~/.config/rice/shader, rice-crt 가
-- 걸 때마다 적는다)을 도로 걸고, 그게 없을 때만 아래 기본값이다. off 로 꺼
-- 뒀으면 off 로 남는다.
local rice_crt = (os.getenv("RICE_REPO") or (os.getenv("HOME") .. "/nixos-config"))
                 .. "/apps/rice/crt"

-- 첫 로그인(아직 아무것도 안 걸어 본 머신)에 걸 것. 갈래/이름 하나여도 되고
-- 체인 이름이어도 된다:
--   "crt/crt"  "water/still"  "chain/bad-signal"  "off"
-- 한 번이라도 스위처로 골랐으면 그쪽이 이긴다 — 여기를 고쳐서 바꾸는 게
-- 아니라 apps/rice/crt 로 걸면 된다.
local crt_start = "crt/crt"

-- hl.dsp.exec_cmd 가 아니라 hl.exec_cmd 다. 이름이 같아서 헷갈리는데 뜻이 다르다:
-- dsp 쪽은 **디스패처를 만들어 돌려주고**(그래서 hl.bind 의 인자로 쓴다), 이쪽은
-- 그 자리에서 실행하고 nil 을 돌려준다(share/hypr/stubs/hl.meta.lua). dsp 쪽을
-- 여기에 쓰면 아무 일도 안 일어나고, 증상은 "로그인하면 셰이더가 안 걸린다"다.
hl.exec_cmd(rice_crt .. " --boot " .. crt_start)

